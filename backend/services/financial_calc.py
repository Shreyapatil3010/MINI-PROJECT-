"""
Financial calculations — extracts metrics from PDF page text using regex.
Simple, reliable approach that works with Apple 10-K and similar formats.
"""
import re
import logging
from typing import List, Dict, Optional, Any, Tuple

import numpy as np
from models.schemas import FinancialTable, FinancialMetric

logger = logging.getLogger(__name__)

# ─── Metric definitions ───────────────────────────────────────────────────────
# Order matters — more specific first
METRIC_KEYWORDS: Dict[str, List[str]] = {
    "Revenue":             ["total net sales", "net sales", "total revenue", "net revenue", "total sales"],
    "Gross Profit":        ["gross margin", "gross profit"],
    "Operating Income":    ["operating income", "income from operations"],
    "Net Income":          ["net income", "net earnings"],
    "Total Assets":        ["total assets"],
    "Total Liabilities":   ["total liabilities"],
    "Equity":              ["total shareholders equity", "total stockholders equity", "shareholders equity", "stockholders equity"],
    "Cash":                ["cash and cash equivalents"],
    "EPS":                 ["diluted earnings per share", "basic earnings per share"],
    "Operating Cash Flow": ["net cash generated by operating", "operating activities"],
    "Capital Expenditure": ["purchases of property, plant", "capital expenditures"],
    "Long-term Debt":      ["term debt"],
    "iPhone Revenue":      ["iphone"],
    "Mac Revenue":         ["mac"],
    "Services Revenue":    ["services"],
    "iPad Revenue":        ["ipad"],
}

# Number pattern: matches 1,234 or 1,234.56 or 1234
NUM_RE = re.compile(r'\(?\d{1,3}(?:,\d{3})+(?:\.\d+)?\)?|\(\d+\)')
YEAR_RE = re.compile(r'\b(20\d{2})\b')


def _clean_num(s: str) -> Optional[float]:
    """Parse '29,965' or '(1,234)' → float."""
    s = s.strip()
    negative = s.startswith('(') and s.endswith(')')
    s = s.strip('()')
    s = s.replace(',', '')
    try:
        v = float(s)
        return -v if negative else v
    except ValueError:
        return None


def _match_metric(label: str) -> Optional[str]:
    """Match label to a metric name — longest keyword wins."""
    l = label.lower()
    best, best_len = None, 0
    for name, kws in METRIC_KEYWORDS.items():
        for kw in kws:
            if kw in l and len(kw) > best_len:
                best, best_len = name, len(kw)
    return best


def _get_years_for_page(text: str) -> List[str]:
    """Extract fiscal years from top 400 chars of page text."""
    top = text[:400]
    years = YEAR_RE.findall(top)
    valid = sorted(set(y for y in years if 2010 <= int(y) <= 2030), reverse=True)
    return valid[:5]  # max 5 years


def tables_to_metrics(
    tables: List[FinancialTable],
    page_texts: Optional[Dict[int, str]] = None,
) -> List[FinancialMetric]:
    """
    Extract financial metrics from page texts.
    Falls back to table parsing if page_texts not available.
    """
    if page_texts:
        return _metrics_from_text(page_texts)
    return _metrics_from_tables(tables)


def _metrics_from_text(page_texts: Dict[int, str]) -> List[FinancialMetric]:
    """Main extractor — reads page text line by line."""
    raw: Dict[str, Dict[str, float]] = {}   # metric → {year → value}
    units: Dict[str, str] = {}

    for page_num, text in page_texts.items():
        if not text or len(text) < 20:
            continue

        years = _get_years_for_page(text)
        if not years:
            continue

        # Detect unit
        tl = text[:600].lower()
        unit = ""
        if "in millions" in tl or "dollars in millions" in tl:
            unit = "millions"
        elif "in billions" in tl:
            unit = "billions"
        elif "in thousands" in tl:
            unit = "thousands"

        for line in text.split('\n'):
            line = line.strip()
            if len(line) < 5:
                continue

            # Match metric
            metric_name = _match_metric(line)
            if not metric_name:
                continue

            # Extract numbers from this line
            nums_raw = NUM_RE.findall(line)
            nums = [_clean_num(n) for n in nums_raw]
            nums = [v for v in nums if v is not None and abs(v) > 10]

            if not nums:
                continue

            if metric_name not in raw:
                raw[metric_name] = {}
            if unit and metric_name not in units:
                units[metric_name] = unit

            # Map numbers → years (descending year order)
            for i, yr in enumerate(years):
                if i < len(nums) and yr not in raw[metric_name]:
                    raw[metric_name][yr] = nums[i]

    return _build_metrics(raw, units)


def _metrics_from_tables(tables: List[FinancialTable]) -> List[FinancialMetric]:
    """Fallback: parse structured tables."""
    raw: Dict[str, Dict[str, float]] = {}
    units: Dict[str, str] = {}

    for table in tables:
        # Find year columns
        year_cols: Dict[str, int] = {}
        for i, h in enumerate(table.headers or []):
            m = YEAR_RE.search(str(h))
            if m and 2010 <= int(m.group()) <= 2030:
                year_cols[m.group()] = i

        if not year_cols:
            continue

        header_txt = ' '.join(str(h) for h in (table.headers or [])).lower()
        unit = "millions" if "million" in header_txt else ("billions" if "billion" in header_txt else "")

        for row in table.rows:
            if not row:
                continue
            label = str(row[0]).lower().strip() if row[0] else ""
            metric_name = _match_metric(label)
            if not metric_name:
                continue
            if metric_name not in raw:
                raw[metric_name] = {}
            if unit and metric_name not in units:
                units[metric_name] = unit
            for yr, col in year_cols.items():
                if col < len(row):
                    v = _clean_num(str(row[col]).replace(',', '')) if row[col] else None
                    if v is not None and yr not in raw[metric_name]:
                        raw[metric_name][yr] = v

    return _build_metrics(raw, units)


def _build_metrics(
    raw: Dict[str, Dict[str, float]],
    units: Dict[str, str],
) -> List[FinancialMetric]:
    result = []
    for name, year_vals in raw.items():
        valid = {yr: v for yr, v in year_vals.items() if v != 0}
        if not valid:
            continue
        sorted_yrs = sorted(valid)
        change_pct: Dict[str, float] = {}
        for i in range(1, len(sorted_yrs)):
            prev = valid[sorted_yrs[i-1]]
            curr = valid[sorted_yrs[i]]
            if prev and prev != 0:
                change_pct[sorted_yrs[i]] = round((curr - prev) / abs(prev) * 100, 2)
        result.append(FinancialMetric(
            name=name,
            values=valid,
            unit=units.get(name, ""),
            change_pct=change_pct or None,
        ))
    return result


# ─── Stats ────────────────────────────────────────────────────────────────────

def compute_summary_stats(metric: FinancialMetric) -> Dict[str, Any]:
    vals = list(metric.values.values())
    if not vals:
        return {}
    arr = np.array(vals, dtype=float)
    return {
        "min": float(np.min(arr)), "max": float(np.max(arr)),
        "mean": float(np.mean(arr)), "median": float(np.median(arr)),
        "std": float(np.std(arr)),
        "total_growth_pct": round((arr[-1]-arr[0])/abs(arr[0])*100, 2) if arr[0] != 0 else None,
        "cagr": _cagr(arr[0], arr[-1], len(arr)-1),
    }


def _cagr(s: float, e: float, n: int) -> Optional[float]:
    if n <= 0 or s <= 0 or e <= 0:
        return None
    return round((pow(e/s, 1/n) - 1) * 100, 2)


def find_inconsistencies(metrics: List[FinancialMetric]) -> List[str]:
    flags = []
    lk = {m.name: m for m in metrics}
    rev, ni = lk.get("Revenue"), lk.get("Net Income")
    if rev and ni and rev.change_pct and ni.change_pct:
        for yr in ni.change_pct:
            if yr in rev.change_pct and ni.change_pct[yr] > rev.change_pct[yr] + 50:
                flags.append(f"{yr}: Net Income grew {ni.change_pct[yr]:.1f}% vs Revenue {rev.change_pct[yr]:.1f}% — possible one-time gain.")
    eq = lk.get("Equity")
    if eq:
        for yr, v in eq.values.items():
            if v < 0:
                flags.append(f"{yr}: Negative equity — potential financial distress.")
    if rev and rev.change_pct:
        for yr, c in rev.change_pct.items():
            if c < -20:
                flags.append(f"{yr}: Revenue dropped {c:.1f}%.")
    debt = lk.get("Long-term Debt")
    if debt and debt.change_pct:
        for yr, c in debt.change_pct.items():
            if c > 50:
                flags.append(f"{yr}: Long-term Debt +{c:.1f}% — significant leverage increase.")
    return flags


def diff_metrics(
    a: List[FinancialMetric], b: List[FinancialMetric],
    a_name: str, b_name: str,
) -> List[Dict[str, Any]]:
    la, lb = {m.name: m for m in a}, {m.name: m for m in b}
    diffs = []
    for name in sorted(set(la) | set(lb)):
        d: Dict[str, Any] = {"metric": name}
        if name in la: d[f"{a_name}_values"] = la[name].values
        if name in lb: d[f"{b_name}_values"] = lb[name].values
        if name in la and name in lb:
            overlap = set(la[name].values) & set(lb[name].values)
            d["deltas"] = {yr: round(lb[name].values[yr] - la[name].values[yr], 2) for yr in overlap}
        diffs.append(d)
    return diffs
